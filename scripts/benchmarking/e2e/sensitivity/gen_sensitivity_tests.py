#!/usr/bin/env python3
"""Generate the .test files, sweep configurations and cell lists of the implementation-selection sensitivity runs.

Part B, SARAD (queries/sensitivity/sarad.test): the batch-rate query, whose choices depend on the fill time alone, with a model
whose invocation is comparable to the window slide, so that the keep-up constraint and the profile can change the choice. The
window is CWRU's: 200 ms at 48,000 tuples/s are the model's 9600 samples.

Part C, window scaling (queries/sensitivity/nbeats_w<W>.test): the batch-rate query at other wall-clock window sizes, to find
out whether the latency that the profile does not cover scales with the window, as f assumes. The window stays 75 samples of
event time, which is the model's input, while the source replays it faster or slower, so W = 75 ms / speedup. The advances are
chosen so that batch sizes land where the two readings of the margin disagree: within f * W but closer than the ~5 ms of
measured overhead to W (W = 37.5 ms), or beyond f * W but clear of W (W = 150, 300 ms).

Every cell is written to cells_<name>.txt as "<section> <config> <repetitions>", which run_sensitivity_sweep.sh runs.

    ./gen_sensitivity_tests.py --output queries/sensitivity --project-root /home/gaturchenko/navi
"""

import argparse
from pathlib import Path

HEADER = """# Generated by gen_sensitivity_tests.py; see there.
GlobalConfiguration worker.query_engine.number_of_worker_threads: [2]
GlobalConfiguration worker.default_query_execution.inference.use_batch_deduplication: [false]
GlobalConfiguration worker.default_query_execution.inference.prediction_cache_type: [NONE]
GlobalConfiguration worker.default_query_execution.inference.openvino_inference_num_threads: [4]
GlobalConfiguration worker.default_query_execution.inference.openvino_num_streams: [1]
GlobalConfiguration worker.default_query_execution.inference.openvino_enable_cpu_pinning: [false]
GlobalConfiguration worker.default_query_execution.operator_buffer_size: [131072]
GlobalConfiguration worker.default_query_execution.page_size: [4096]
GlobalConfiguration worker.number_of_buffers_in_global_buffer_manager: [8192]

CREATE LOGICAL SOURCE series(timestamp UINT64 NOT NULL, value FLOAT32 NOT NULL);
CREATE PHYSICAL SOURCE FOR series TYPE TCP SET(
    {rate} AS `SOURCE`.MOCK_TUPLE_RATE,
    1 AS `SOURCE`.FLUSH_INTERVAL_MS
);
ATTACH FILE {data}

CREATE SINK latencySink(
    {output} VARSIZED NOT NULL,
    ingestion_time UINT64 NOT NULL
) TYPE LATENCY SET (
    '{results}/latency_timings.csv' AS `SINK`.log_path,
    'ingestion_time' AS `SINK`.ingest_field
);

CREATE MODEL {model} ('{model_path}')
INPUT ({input} VARSIZED)
OUTPUT ({output} VARSIZED);
"""

QUERY = """
# ADVANCE {advance} ms
SELECT {output}, ingestion_time
FROM MODEL_INFERENCE({model}, (
        SELECT ARRAY_AGG(value) AS {input}, MAX(ingestion_time) AS ingestion_time
        FROM (SELECT timestamp, value, CURRENT_TIME() AS ingestion_time FROM series)
        WINDOW SLIDING(timestamp, SIZE {size} ms, ADVANCE BY {advance} ms)
    )
)
INTO latencySink;
----
"""

# Part B: slide [ms] -> fixed batch sizes. Candidates stop at W / S; 1 and 2 cannot keep up at 20-25 ms, where they mark the
# overload side, and at 40-50 ms 1 is what any lower f would fall back to.
SARAD_CELLS = {20: [2, 4, 8], 25: [2, 4, 8], 40: [1, 2, 4], 50: [1, 2, 4]}
# The optimizer itself at the default and at the u_max for which the replay predicts other batch sizes.
SARAD_UTILIZATIONS = [0.8, 0.9]
# Where the utilization of batch size 4 crosses 1: the sweep above leaves 0.83 to 1.28 unmeasured, and capacity is about 0.95 B/t(B),
# so these slides bound u_max from above. Batch size 8 is what the optimizer falls back to when it rejects 4.
SARAD_KNEE_CELLS = {19: [4, 8], 18: [4, 8], 17: [4, 8], 16: [4, 8]}

# Part C: wall-clock window [ms] -> (speedup, event-time advance [ms] -> the batch sizes either side of f * W).
WINDOWS = {
    37.5: (2.0, {2: [16, 32], 4: [8, 16], 9: [4, 8], 21: [2, 4]}),
    150.0: (0.5, {1: [32, 64], 2: [16, 32], 10: [4, 8], 23: [2, 4]}),
    300.0: (0.25, {1: [32, 64], 5: [8, 16], 10: [4, 8], 23: [2, 4]}),
}
RUN_SECONDS = 60


def write_config(path: Path, entries: dict) -> None:
    path.write_text("".join(f'"{key}": {value}\n' for key, value in entries.items()), encoding="utf-8")


def fixed_config(output: Path, batch_size: int) -> str:
    name = f"fixed_{batch_size}"
    write_config(
        output / f"{name}.yaml",
        {"optimizer.inference_batch_size_strategy": '["FIXED"]', "optimizer.inference_batch_size": f"[{batch_size}]"},
    )
    return name


def chooses_config(output: Path, max_utilization: float, speedup: float) -> str:
    name = f"chooses_u{max_utilization}_x{speedup}"
    write_config(
        output / f"{name}.yaml",
        {
            "optimizer.inference_batch_size_strategy": '["OPTIMIZER_CHOOSES"]',
            "optimizer.inference_max_utilization": f"[{max_utilization}]",
            "optimizer.inference_latency_slo_fraction": "[0.9]",
            "optimizer.inference_replay_speedup": f"[{speedup}]",
        },
    )
    return name


def write_sarad(output: Path, root: str) -> None:
    write_sarad_cells(output, root, "sarad", SARAD_CELLS, SARAD_UTILIZATIONS)
    write_sarad_cells(output, root, "sarad_knee", SARAD_KNEE_CELLS, [])


def write_sarad_cells(output: Path, root: str, name: str, slides: dict, utilizations: list) -> None:
    model = {
        "model": "sarad",
        "model_path": f"{root}/models-benchmarking/models/sarad/sarad_medium.onnx",
        "input": "value_200_ms",
        "output": "anomaly_score",
    }
    text = HEADER.format(rate=48000, data=f"{root}/datasets/synthetic/sensitivity_sarad.csv", results=f"results/sensitivity/{name}", **model)
    cells = []
    for section, (advance, batch_sizes) in enumerate(slides.items(), start=1):
        text += QUERY.format(advance=advance, size=200, **model)
        cells += [f"{section:02d} {fixed_config(output, batch_size)} 3" for batch_size in batch_sizes]
        cells += [f"{section:02d} {chooses_config(output, utilization, 1.0)} 3" for utilization in utilizations]
    (output / f"{name}.test").write_text(text, encoding="utf-8")
    (output / f"cells_{name}.txt").write_text("\n".join(cells) + "\n", encoding="utf-8")


def write_windows(output: Path, root: str) -> None:
    model = {
        "model": "nbeats300",
        "model_path": f"{root}/models-benchmarking/models/nbeats/nbeats_size_300_stride_30.onnx",
        "input": "value_75_ms",
        "output": "forecast",
    }
    for window, (speedup, advances) in WINDOWS.items():
        name = f"nbeats_w{int(window)}"
        rate = int(1000 * speedup)
        rows = RUN_SECONDS * rate
        text = HEADER.format(rate=rate, data=f"{root}/datasets/synthetic/sensitivity_nbeats_{rows}.csv", results=f"results/sensitivity/{name}", **model)
        cells = []
        for section, (advance, batch_sizes) in enumerate(advances.items(), start=1):
            text += QUERY.format(advance=advance, size=75, **model)
            cells += [f"{section:02d} {fixed_config(output, batch_size)} 3" for batch_size in batch_sizes]
            # The choice is a pure function of the profile, so one deployment checks it.
            cells.append(f"{section:02d} {chooses_config(output, 0.8, speedup)} 1")
        (output / f"{name}.test").write_text(text, encoding="utf-8")
        (output / f"cells_{name}.txt").write_text("\n".join(cells) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--project-root", default="/home/gaturchenko/navi")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    write_sarad(args.output, args.project_root)
    write_windows(args.output, args.project_root)


if __name__ == "__main__":
    main()
