#!/usr/bin/env python3
"""Generate the post-join batching experiment's .test files, one per k (a .test cannot vary the arity of a join).

post_join_k<K>.test joins k MUSAN-like audio streams on their window start and infers MHAtt-RNN on each stream's 1 s
window, written as k nested MODEL_INFERENCE calls that the PostJoinInference rewrite turns into one inference operator
over k payloads. That operator either invokes the model once with a batch of k (BATCHED) or k times with one payload
(SEQUENTIAL); the swept optimizer.post_join_inference_strategy picks one or lets OPTIMIZER_CHOOSES profile both.

Sections, one per window ADVANCE (= the join's tumbling window, so one joined record per ADVANCE):
    inference sections   the experiment; a shorter ADVANCE raises the joined-record rate 1000 / ADVANCE per second
    join-only sections   (--control-advances) the same windows and joins without inference, to show where the source,
                         windowing and joins cap the rate rather than the model

    ./gen_post_join_tests.py --data-dir /home/<user>/navi/datasets/post_join --output-dir queries/post-join \
        --model /home/<user>/navi/models-benchmarking/models/mhatt-rnn/saved_model
"""

import argparse
from pathlib import Path

HEADER = """\
#  Post-join batching experiment, k = {k} (generated by gen_post_join_tests.py; edit the generator, not this file).
#
#  {k} audio streams (16 kHz, replayed in real time by the TCP mock source), each aggregated into 1 s sliding windows,
#  joined on the window start and fed into MHAtt-RNN once per stream. Sections:
{sections}
#
#  The latency sink measures from the last sample of stream 0's window (ingestion_time) to the joined record's sink.

GlobalConfiguration worker.query_engine.number_of_worker_threads: [{worker_threads}]
GlobalConfiguration worker.default_query_execution.inference.prediction_cache_type: [NONE]
GlobalConfiguration worker.default_query_execution.inference.openvino_inference_num_threads: [1]
GlobalConfiguration worker.default_query_execution.inference.openvino_num_streams: [0]
GlobalConfiguration worker.default_query_execution.inference.openvino_enable_cpu_pinning: [false]
GlobalConfiguration worker.default_query_execution.inference.openvino_share_compiled_model: [false]
GlobalConfiguration worker.default_query_execution.operator_buffer_size: [131072]
GlobalConfiguration worker.default_query_execution.page_size: [16384]
GlobalConfiguration worker.default_max_inflight_buffers: [16]
GlobalConfiguration worker.number_of_buffers_in_global_buffer_manager: [12228]
"""

SOURCE = """\
CREATE LOGICAL SOURCE {name}(timestamp UINT64 NOT NULL, audioSample INT16 NOT NULL);
CREATE PHYSICAL SOURCE FOR {name} TYPE TCP SET(
  16000 AS `SOURCE`.MOCK_TUPLE_RATE
);
ATTACH FILE {data}
"""

MODEL = """\
CREATE MODEL mhatt_rnn ('{model}')
INPUT (audio1sec VARSIZED)
OUTPUT (keywordProb VARSIZED);
"""


def source_name(i: int) -> str:
    return f"stream{i}"


def window(i: int, advance_ms: int) -> str:
    """Stream i's 1 s sliding window; stream 0 also carries the ingestion time the latency sink measures from."""
    name = source_name(i)
    if i == 0:
        return f"""SELECT
    start,
    UINT8(1) AS joinKey{i},
    ARRAY_AGG(audioSample / FLOAT32(32767.0)) AS audio1sec,
    MAX(ingestion_time) AS ingestion_time
FROM (
    SELECT timestamp, audioSample, CURRENT_TIME() AS ingestion_time
    FROM {name}
)
WINDOW SLIDING(timestamp, SIZE 1 sec, ADVANCE BY {advance_ms} ms)"""
    return f"""SELECT
    start,
    UINT8(1) AS joinKey{i},
    ARRAY_AGG(audioSample / FLOAT32(32767.0)) AS audio1sec
FROM {name}
WINDOW SLIDING(timestamp, SIZE 1 sec, ADVANCE BY {advance_ms} ms)"""


def indent(text: str, by: int = 4) -> str:
    return "\n".join((" " * by + line) if line else line for line in text.splitlines())


def joined(k: int, advance_ms: int) -> str:
    """Left-deep chain of window joins over streams 0..k-1, as in queries/musan/ablation_musan_lat.test."""
    query = window(0, advance_ms)
    for i in range(1, k):
        query = f"""SELECT *
FROM (
{indent(query)}
)
JOIN (
{indent(window(i, advance_ms))}
)
ON joinKey0 = joinKey{i}
WINDOW TUMBLING(start, SIZE {advance_ms} ms)"""
    return query


def inference_query(k: int, advance_ms: int) -> str:
    projection = ",\n".join(f"    {source_name(i)}.keywordProb AS {source_name(i)}_keywordProb" for i in range(k))
    opening = "MODEL_INFERENCE(mhatt_rnn, " * k
    closing = ")" * k
    return f"""# Inference, ADVANCE {advance_ms} ms ({1000 / advance_ms:g} joined records/s)
SELECT
{projection},
    {source_name(0)}.ingestion_time AS ingestion_time
FROM {opening}(
{indent(joined(k, advance_ms))}
){closing}
INTO postJoinLatency;
----
"""


def join_only_query(k: int, advance_ms: int) -> str:
    # The sink's payload fields carry the windows themselves, so the record shape stays VARSIZED x k.
    projection = ",\n".join(f"    {source_name(i)}.audio1sec AS {source_name(i)}_keywordProb" for i in range(k))
    return f"""# Join only, ADVANCE {advance_ms} ms ({1000 / advance_ms:g} joined records/s)
SELECT
{projection},
    {source_name(0)}.ingestion_time AS ingestion_time
FROM (
{indent(joined(k, advance_ms))}
)
INTO postJoinLatency;
----
"""


def generate(k: int, advances: list[int], control_advances: list[int], args: argparse.Namespace) -> str:
    sections = [(f"inference, ADVANCE {a} ms", inference_query(k, a)) for a in advances]
    sections += [(f"join only, ADVANCE {a} ms", join_only_query(k, a)) for a in control_advances]
    listing = "\n".join(f"#    :{n:02d} {label}" for n, (label, _) in enumerate(sections, start=1))

    parts = [HEADER.format(k=k, sections=listing, worker_threads=args.worker_threads)]
    parts += [SOURCE.format(name=source_name(i), data=args.data_dir / f"stream{i}.csv") for i in range(k)]
    parts.append(MODEL.format(model=args.model))
    fields = "\n".join(f"    {source_name(i)}_keywordProb VARSIZED NOT NULL," for i in range(k))
    parts.append(f"""CREATE SINK postJoinLatency(
{fields}
    ingestion_time UINT64 NOT NULL
) TYPE LATENCY SET (
    '{args.latency_log}' AS `SINK`.log_path,
    'ingestion_time' AS `SINK`.ingest_field
);
""")
    parts += [query for _, query in sections]
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ks", type=int, nargs="+", default=[2, 3, 4, 6, 8])
    parser.add_argument("--advances-ms", type=int, nargs="+", default=[333, 200, 125, 80, 50])
    parser.add_argument("--control-advances-ms", type=int, nargs="*", default=[50])
    parser.add_argument("--data-dir", type=Path, required=True, help="Absolute directory of gen_post_join_data.py's streams.")
    parser.add_argument("--model", type=Path, required=True, help="Absolute path of the MHAtt-RNN SavedModel.")
    parser.add_argument("--latency-log", default="results/post_join/latency_timings.csv")
    parser.add_argument("--worker-threads", type=int, default=2)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for k in args.ks:
        if k < 2:
            parser.error("post-join inference needs k >= 2")
        output = args.output_dir / f"post_join_k{k}.test"
        output.write_text(generate(k, args.advances_ms, args.control_advances_ms, args))
        print(f"{output}: {len(args.advances_ms)} inference + {len(args.control_advances_ms)} join-only sections")


if __name__ == "__main__":
    main()
